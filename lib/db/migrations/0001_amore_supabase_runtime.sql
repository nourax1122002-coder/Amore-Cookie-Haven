create table if not exists public.customer_orders (
  id text primary key,
  number text not null unique,
  cart_hash text not null,
  request_key text not null unique,
  request_hash text not null,
  token_hash text not null,
  phone text not null,
  address jsonb not null,
  note text not null default '',
  items jsonb not null,
  subtotal_fils integer not null check (subtotal_fils >= 0),
  shipping_fils integer not null check (shipping_fils >= 0),
  total_fils integer not null check (total_fils >= 0),
  currency text not null default 'KWD',
  payment_status text not null default 'pending',
  fulfillment_status text not null default 'received',
  invoice_id text unique,
  payment_id text unique,
  payment_url text,
  stock_status text not null default 'unreserved',
  stock_plan jsonb,
  release_plan jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists customer_orders_cart_created_idx
  on public.customer_orders (cart_hash, created_at desc);
create index if not exists customer_orders_reconcile_idx
  on public.customer_orders (updated_at)
  where payment_status in ('pending', 'creating', 'failed', 'cancelled', 'review')
    and stock_status in ('reserved', 'reserving', 'releasing');

create table if not exists public.cafe_inquiries (
  id bigint generated by default as identity primary key,
  cafe_name text not null,
  contact_name text not null,
  phone text not null,
  email text not null,
  area text not null,
  products text not null,
  notes text not null default '',
  request_key text not null unique,
  request_hash text not null,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id text primary key default 'amore',
  content jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.security_counters (
  scope text not null,
  key_hash text not null,
  hits integer not null check (hits >= 1),
  expires_at timestamptz not null,
  primary key (scope, key_hash)
);
create index if not exists security_counters_expiry_idx on public.security_counters (expires_at);

create table if not exists public.app_locks (
  name text primary key,
  owner text not null,
  expires_at timestamptz not null
);

