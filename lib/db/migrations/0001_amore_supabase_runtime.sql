create or replace function public.increment_security_counter(
  p_scope text, p_key_hash text, p_window_ms integer, p_cap integer
) returns table(hits integer, expires_at timestamptz)
language sql security definer set search_path = public, pg_temp
as $$
  insert into public.security_counters as current (scope, key_hash, hits, expires_at)
  values (p_scope, p_key_hash, 1, statement_timestamp() + p_window_ms * interval '1 millisecond')
  on conflict (scope, key_hash) do update set
    hits = case when current.expires_at <= statement_timestamp()
      then 1 else least(current.hits + 1, p_cap) end,
    expires_at = case when current.expires_at <= statement_timestamp()
      then excluded.expires_at else current.expires_at end
  returning current.hits, current.expires_at;
$$;

create or replace function public.delete_security_counter(p_scope text, p_key_hash text)
returns void language sql security definer set search_path = public, pg_temp
as $$
  delete from public.security_counters where scope = p_scope and key_hash = p_key_hash;
$$;

create or replace function public.read_active_security_counter(p_scope text, p_key_hash text)
returns table(expires_at timestamptz)
language sql security definer set search_path = public, pg_temp
as $$
  select c.expires_at from public.security_counters c
  where c.scope = p_scope and c.key_hash = p_key_hash and c.expires_at > statement_timestamp();
$$;

create or replace function public.claim_security_lease(
  p_scope text, p_key_hash text, p_token integer, p_ttl_seconds integer
) returns boolean
language plpgsql security definer set search_path = public, pg_temp
as $$
declare claimed integer;
begin
  insert into public.security_counters as current (scope, key_hash, hits, expires_at)
  values (p_scope, p_key_hash, p_token, statement_timestamp() + greatest(1, p_ttl_seconds) * interval '1 second')
  on conflict (scope, key_hash) do update set
    hits = excluded.hits, expires_at = excluded.expires_at
  where current.expires_at <= statement_timestamp()
  returning 1 into claimed;
  return claimed = 1;
end;
$$;

create or replace function public.release_security_lease(p_scope text, p_key_hash text, p_token integer)
returns void language sql security definer set search_path = public, pg_temp
as $$
  delete from public.security_counters
  where scope = p_scope and key_hash = p_key_hash and hits = p_token;
$$;

create or replace function public.set_security_cooldown(p_scope text, p_key_hash text, p_ttl_seconds integer)
returns void language sql security definer set search_path = public, pg_temp
as $$
  insert into public.security_counters as current (scope, key_hash, hits, expires_at)
  values (p_scope, p_key_hash, 1, statement_timestamp() + greatest(1, least(86400, p_ttl_seconds)) * interval '1 second')
  on conflict (scope, key_hash) do update set
    expires_at = greatest(current.expires_at, excluded.expires_at);
$$;

create or replace function public.prune_security_counters()
returns integer language plpgsql security definer set search_path = public, pg_temp
as $$
declare removed integer;
begin
  with expired as (
    select scope, key_hash from public.security_counters
    where expires_at <= statement_timestamp()
    order by expires_at limit 10000
  )
  delete from public.security_counters c using expired e
  where c.scope = e.scope and c.key_hash = e.key_hash
    and c.expires_at <= statement_timestamp();
  get diagnostics removed = row_count;
  return removed;
end;
$$;

create or replace function public.acquire_named_lock(p_name text, p_owner text, p_lease_ms integer)
returns boolean
language plpgsql security definer set search_path = public, pg_temp
as $$
declare claimed integer;
begin
  insert into public.app_locks as current (name, owner, expires_at)
  values (p_name, p_owner, statement_timestamp() + greatest(1000, p_lease_ms) * interval '1 millisecond')
  on conflict (name) do update set owner = excluded.owner, expires_at = excluded.expires_at
  where current.expires_at <= statement_timestamp()
  returning 1 into claimed;
  return claimed = 1;
end;
$$;

create or replace function public.renew_named_lock(p_name text, p_owner text, p_lease_ms integer)
returns boolean
language plpgsql security definer set search_path = public, pg_temp
as $$
declare renewed integer;
begin
  update public.app_locks set expires_at = statement_timestamp() + greatest(1000, p_lease_ms) * interval '1 millisecond'
  where name = p_name and owner = p_owner and expires_at > statement_timestamp()
  returning 1 into renewed;
  return renewed = 1;
end;
$$;

create or replace function public.release_named_lock(p_name text, p_owner text)
returns void language sql security definer set search_path = public, pg_temp
as $$
  delete from public.app_locks where name = p_name and owner = p_owner;
$$;

